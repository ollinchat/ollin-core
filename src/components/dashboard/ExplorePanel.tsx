    if (tabsEditMode) return;
    clearTabLongPressTimer();
    tabLongPressTimerRef.current = setTimeout(() => {
      tabLongPressTimerRef.current = null;
      suppressNextTabClickRef.current = true;
      setTabsEditMode(true);
    }, 500);
